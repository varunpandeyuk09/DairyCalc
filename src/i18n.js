export function makeT(lang) {
  const dict = STRINGS[lang] || STRINGS.hi
  return (key) => dict[key] ?? STRINGS.hi[key] ?? key
}

export function productName(product, lang) {
  if (!product) return ''
  return (lang === 'hi' ? product.nameHi : product.nameEn) || product.nameHi || product.nameEn || ''
}
